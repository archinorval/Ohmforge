#!/usr/bin/env bash
# Regenerate the ngspice reference ("golden") data for the of-analog
# comparison tests.
#
# ngspice is used ONLY as an external program to produce data files. It is
# never linked, vendored or shipped with Ohmforge (most of ngspice is BSD,
# but one GPL file exists in its tree; running the binary keeps us clear of
# it entirely).
#
# Usage: NGSPICE=/path/to/ngspice scripts/gen-ngspice-golden.sh
set -euo pipefail
NGSPICE="${NGSPICE:-ngspice}"
root="$(cd "$(dirname "$0")/.." && pwd)"
cir_dir="$root/crates/of-analog/tests/circuits"
out_dir="$root/crates/of-analog/tests/golden"
mkdir -p "$out_dir"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
version="$("$NGSPICE" -v 2>/dev/null | grep -o 'ngspice-[0-9.]*' | head -1)"
for cir in "$cir_dir"/*.cir; do
  name="$(basename "$cir" .cir)"
  vecs="$(sed -n 's/^\* compare: //p' "$cir")"
  deck="$tmp/$name.cir"
  # Deck without .end, plus a control block that writes the vectors.
  grep -vi '^\.end$' "$cir" > "$deck"
  cat >> "$deck" <<CTRL
.control
set wr_singlescale
set wr_vecnames
option numdgt=12
run
wrdata $tmp/$name.dat $vecs
.endc
.end
CTRL
  "$NGSPICE" -b "$deck" > "$tmp/$name.log" 2>&1 || { cat "$tmp/$name.log"; exit 1; }
  {
    echo "# Generated by $version (external tool) from tests/circuits/$name.cir; do not edit."
    echo "# columns: scale $vecs"
    tail -n +2 "$tmp/$name.dat" | awk '{$1=$1; gsub(/ /, ","); print}'
  } > "$out_dir/$name.csv"
  echo "$name: $(($(wc -l < "$out_dir/$name.csv") - 2)) rows"
done
